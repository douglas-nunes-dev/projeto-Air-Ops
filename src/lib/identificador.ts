// Identificador único (UUID v4) gerado no aparelho, ex.: o id da foto antes de enviar.
// crypto.randomUUID só existe em HTTPS ou localhost; pelo endereço da rede local
// (http://192.168…) ele não existe, então monta o mesmo formato com getRandomValues.
export function gerarId(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();

  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // versão 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variante RFC 4122
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
